"""Generate src/dxf-template.js: an empty, valid DXF R2000 drawing (inches) made by ezdxf.
The app inserts LINE/ARC entities into it, so the file stays a real R2000 DXF with $INSUNITS=1."""
import io, json, sys
import ezdxf

doc = ezdxf.new("R2000", setup=False)
doc.units = 1                      # $INSUNITS = 1 -> inches
doc.header["$MEASUREMENT"] = 0     # imperial
doc.header["$LUNITS"] = 2          # decimal
# layers are added by the app per export (one per cut type), see @@LAYERS@@ below
s = io.StringIO()
doc.write(s)
text = s.getvalue()

lines = text.split("\n")
# Placeholders: handseed, extents, entities
def replace_header_value(var, code_values):
    i = lines.index(var)
    j = i + 1
    for code, val in code_values:
        assert lines[j].strip() == code, (var, lines[j])
        lines[j + 1] = val
        j += 2
replace_header_value("$HANDSEED", [("5", "@@HANDSEED@@")])
replace_header_value("$EXTMIN", [("10", "@@MINX@@"), ("20", "@@MINY@@"), ("30", "0.0")])
replace_header_value("$EXTMAX", [("10", "@@MAXX@@"), ("20", "@@MAXY@@"), ("30", "0.0")])
# LAYER table: the app fills in its own layer records and the count
t = next(i for i in range(len(lines) - 2) if lines[i].strip() == "TABLE" and lines[i + 2].strip() == "LAYER")
j = t
while lines[j].strip() != "AcDbSymbolTable": j += 1
assert lines[j + 1].strip() == "70"
base_layers = int(lines[j + 2])
lines[j + 2] = "@@LAYERCOUNT@@"
e = j
while lines[e].strip() != "ENDTAB": e += 1
lines.insert(e - 1, "@@LAYERS@@")  # before the "0" that precedes ENDTAB
layer_table = doc.layers.head.dxf.handle
plot_style = doc.layers.get("0").dxf.plotstyle_handle
k = lines.index("ENTITIES")
lines.insert(k + 1, "@@ENTITIES@@")
# Find model space block record handle
ms = doc.modelspace().block_record.dxf.handle
seed = doc.header["$HANDSEED"]
out = "\n".join(lines)
js = ("// Generated by tools/make_dxf_template.py from ezdxf %s. Do not edit by hand.\n"
      "export const DXF_R2000_TEMPLATE = %s;\n"
      "export const MODEL_SPACE_HANDLE = %s;\n"
      "export const FIRST_FREE_HANDLE = 0x%s;\n"
      "export const LAYER_TABLE_HANDLE = %s;\n"
      "export const PLOT_STYLE_HANDLE = %s;\n"
      "export const BASE_LAYER_COUNT = %d;\n") % (ezdxf.__version__, json.dumps(out), json.dumps(ms), seed,
                                                json.dumps(layer_table), json.dumps(plot_style), base_layers)
open(sys.argv[1], "w").write(js)
print("template bytes", len(out), "model space", ms, "seed", seed)
